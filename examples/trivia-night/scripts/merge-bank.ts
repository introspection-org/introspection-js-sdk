/**
 * Merge the generated questions that passed their check into the larger bank:
 * keep `ok` and `fix` verdicts (applying the fix), drop any question that
 * repeats an existing one or another new one, and write lib/questions-large.ts.
 *
 *   node --import tsx scripts/merge-bank.ts
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { GENRES, type Question } from "../lib/question-types";
import { MORE_QUESTIONS } from "../lib/questions-more";

const DIR = "improve/bank";
const PREFIX: Record<string, string> = {
  music: "mu",
  film: "fi",
  sport: "sp",
  science: "sc",
  history: "hi",
  geography: "ge",
};
const STOP = new Set([
  "the",
  "a",
  "an",
  "of",
  "in",
  "which",
  "what",
  "who",
  "is",
  "was",
  "did",
  "to",
  "and",
  "for",
  "by",
  "on",
]);
const words = (text: string) =>
  new Set(
    text
      .toLowerCase()
      .replace(/[^a-z0-9 ]/g, " ")
      .split(/\s+/)
      .filter((w) => w && !STOP.has(w)),
  );
const norm = (text: string) => [...words(text)].sort().join(" ");
const overlap = (a: Set<string>, b: Set<string>) =>
  [...a].filter((w) => b.has(w)).length / Math.max(1, Math.min(a.size, b.size));

// The base bank (questions.ts minus this file's own output) is what a new question may not repeat.
const base: Array<{ genre: string; text: string; answer: string }> = [
  ...JSON.parse(readFileSync(`${DIR}/existing-music.json`, "utf8")).map(
    (q: Question) => ({ ...q, genre: "music" }),
  ),
  ...GENRES.filter((g) => g !== "music").flatMap((g) =>
    JSON.parse(readFileSync(`${DIR}/existing-${g}.json`, "utf8")).map(
      (q: Question) => ({ ...q, genre: g }),
    ),
  ),
];
void MORE_QUESTIONS;

const kept: Question[] = [];
const report: Record<string, Record<string, number>> = {};
for (const genre of GENRES) {
  const gen = `${DIR}/gen-${genre}.jsonl`;
  const check = `${DIR}/check-${genre}.jsonl`;
  if (!existsSync(gen) || !existsSync(check))
    throw new Error(`missing ${gen} or ${check}`);
  const rows = readFileSync(gen, "utf8")
    .split("\n")
    .filter(Boolean)
    .map((l) => JSON.parse(l));
  const verdicts = new Map<
    number,
    { verdict: string; difficulty?: number; region?: string }
  >(
    readFileSync(check, "utf8")
      .split("\n")
      .filter(Boolean)
      .map((l) => JSON.parse(l))
      .map((v) => [v.line, v]),
  );
  const seen = base
    .filter((q) => q.genre === genre)
    .map((q) => ({
      key: norm(q.text),
      words: words(q.text),
      answer: q.answer.toLowerCase(),
    }));
  const counts = {
    generated: rows.length,
    failed: 0,
    unchecked: 0,
    repeat: 0,
    kept: 0,
  };
  rows.forEach((row, i) => {
    const v = verdicts.get(i + 1);
    if (!v) return void counts.unchecked++;
    if (v.verdict === "drop") return void counts.failed++;
    const text = String(row.text);
    const answer = String(row.answer);
    const key = norm(text);
    const w = words(text);
    if (
      seen.some(
        (s) =>
          s.key === key ||
          (s.answer === answer.toLowerCase() && overlap(s.words, w) >= 0.5),
      )
    )
      return void counts.repeat++;
    seen.push({ key, words: w, answer: answer.toLowerCase() });
    const difficulty = (v.verdict === "fix" && v.difficulty) || row.difficulty;
    const region = (v.verdict === "fix" && v.region) || row.region;
    kept.push({
      id: `${PREFIX[genre]}-l${String(++counts.kept).padStart(3, "0")}`,
      genre,
      region,
      difficulty,
      text,
      answer,
      aliases: Array.isArray(row.aliases)
        ? row.aliases.map(String).slice(0, 3)
        : [],
    } as Question);
  });
  report[genre] = counts;
}

writeFileSync(
  "lib/questions-large.ts",
  `import type { Question } from "./question-types";\n\n/** Generated by scripts/merge-bank.ts from improve/bank: checked, deduplicated questions. */\nexport const LARGE_QUESTIONS: Question[] = JSON.parse(\n  ${JSON.stringify(JSON.stringify(kept))},\n);\n`,
);
console.log(JSON.stringify(report));
console.log(`kept ${kept.length}`);
